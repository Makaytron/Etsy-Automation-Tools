export const UI_LANGUAGES = Object.freeze([
  Object.freeze({ code: 'en', name: 'English', english: 'English' }),
  ...PACK_LANGUAGES.map((code) => Object.freeze({ code, name: PACK_NAMES[code], english: englishName(code) })),
]);
