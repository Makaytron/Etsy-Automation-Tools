#!/usr/bin/env node
// Turns the design canvas's stylesheets into the CSS of the script's shadow root.
//
// Sources (copied unchanged from the design canvas "Makaytron Etsy Automation Tools — Birleşik Panel"):
//   src/ui/design/suite.css    the canvas's shared stylesheet
//   src/ui/design/screens.css  every artboard's own <style>, clashing names renamed per screen
// Output: src/ui/suite-css.js (SUITE_CSS).
//
// The canvas styles a whole page; the script lives in a closed shadow root on Etsy. So:
// - `:root` tokens move to `.mkui-root`, page globals (`*`, `body`, `a`, `p`, form controls, focus)
//   are scoped with `:where(.mkui-root)`, which keeps their specificity as low as in the canvas;
// - the canvas's logo upload becomes `var(--mk-logo)`, set from the bundled logo at runtime;
// - `.theme-dark` no longer paints a page background (the root is a transparent overlay).
//
// node tools/Unified-Design-Css.mjs           check that src/ui/suite-css.js is current
// node tools/Unified-Design-Css.mjs --write   regenerate it

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SUITE = path.join(repoRoot, 'src', 'ui', 'design', 'suite.css');
const SCREENS = path.join(repoRoot, 'src', 'ui', 'design', 'screens.css');
const OUT = path.join(repoRoot, 'src', 'ui', 'suite-css.js');

function fail(message) {
  console.error(`FAIL design css: ${message}`);
  process.exit(1);
}

function scope(css) {
  const replacements = [
    [/^:root\{/m, '.mkui-root{'],
    [/^\*\{box-sizing:border-box\}$/m, ':where(.mkui-root),:where(.mkui-root) *,:where(.mkui-root) *::before,:where(.mkui-root) *::after{box-sizing:border-box}'],
    [/^body\{margin:0;([^}]*);background:#fff\}$/m, '.mkui-root{$1}'],
    [/^a\{color:var\(--fg\)\}a:hover\{color:var\(--ink2\)\}$/m, ':where(.mkui-root) a{color:var(--fg)}:where(.mkui-root) a:hover{color:var(--ink2)}'],
    [/^button,input,select,textarea\{font-family:inherit\}$/m, ':where(.mkui-root) :is(button,input,select,textarea){font-family:inherit}'],
    [/^:focus-visible\{/m, ':where(.mkui-root) :focus-visible{'],
    [/^p\{margin:0\}$/m, ':where(.mkui-root) p{margin:0}'],
    [/^\.theme-dark\{background:#0b0b0b\}$/m, ''],
  ];
  let out = css;
  for (const [pattern, replacement] of replacements) {
    if (!pattern.test(out)) fail(`suite.css no longer has ${pattern}`);
    out = out.replace(pattern, replacement);
  }
  return out;
}

export function build() {
  const suite = fs.readFileSync(SUITE, 'utf8');
  const screens = fs.readFileSync(SCREENS, 'utf8');
  let css = `${scope(suite)}\n${screens}`;
  css = css.replace(/url\(\/_blob\/[0-9a-f]+\)/g, 'var(--mk-logo,none)');
  // The embedded fonts are registered as "MK Inter" and "MK JetBrains Mono" (see the build).
  css = css.replace(/"Inter"/g, '"MK Inter","Inter"').replace(/"JetBrains Mono"/g, '"MK JetBrains Mono","JetBrains Mono"');
  if (/\/_blob\//.test(css)) fail('an upload address is left in the CSS');
  if (/(^|[\s,}])(body|html|:root)\s*[{,]/m.test(css)) fail('a page-level selector is left unscoped');
  const escaped = css.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${');
  return `// Generated by tools/Unified-Design-Css.mjs from src/ui/design/suite.css and screens.css. Do not edit.\n// Design source: the canvas "Makaytron Etsy Automation Tools — Birleşik Panel", an adaptation of the\n// registered template (template.theme.tokens and the primitives) and shadcn.dashboard.applied.\n\nexport const SUITE_CSS = \`${escaped}\`;\n`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = build();
  if (process.argv.includes('--write')) {
    fs.writeFileSync(OUT, next);
    console.log(`Wrote ${path.relative(repoRoot, OUT)} (${next.length} characters).`);
  } else {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== next) fail('src/ui/suite-css.js is stale; run node tools/Unified-Design-Css.mjs --write');
    console.log('PASS design css: src/ui/suite-css.js matches the design stylesheets.');
  }
}
